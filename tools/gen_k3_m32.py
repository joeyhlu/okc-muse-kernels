"""gen_k3_m32.py: kernels/muse_decode_layer/k3_m32_1.py = k3_gd_1 + the M32 WSK rider (bucket 32: warp-0 weighted hot cut +
hot_w4 8), and k3_m32_2.py = k3_m32_1 + PX at bucket 32 (tools/m32_patches.py, tools/m32_px.py).

Composition: tools/gen_k3_gd.py's chain up to its strip step (k3_v39 regenerated by gen_k3_v37 --v39 and asserted
byte-identical to the file on disk, gd_patches.apply, k3-gd-1 nonce; strip_layer of that text is asserted equal to
k3_gd_1.py on disk), then m32_patches.apply (every anchor asserted unique), the new nonce, tools/strip_layer.py
(AST-equivalence asserted), tools/strip_cxx.py (AST-checked), then gen_k3_gd's checks: compiles, ASCII, line 1, nonce, no
duplicate top-level names, judge-checker scan <= base, < 1 MB.

    python -I tools/gen_k3_m32.py [--only=1|2] [--check]
"""
import ast
import re
import hashlib
import pathlib
import py_compile
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
CHECK = "--check" in sys.argv
ONLY = next((int(a[7:]) for a in sys.argv if a.startswith("--only=")), 0)
_argv, sys.argv = sys.argv, [sys.argv[0]]   # gen_k3_gd parses --n / --check at import
import gen_k3_gd as GD  # noqa: E402
sys.argv = _argv
import gd_patches  # noqa: E402
import m32_patches  # noqa: E402
import strip_cxx  # noqa: E402
import strip_layer  # noqa: E402

G37 = GD.G37
GD1 = ROOT / "kernels/muse_decode_layer/k3_gd_1.py"
OUTS = {
    1: (ROOT / "kernels/muse_decode_layer/k3_m32_1.py", "k3-m32-1",
        "# nonce k3-m32-1 (k3_gd_1 + M32 rider: bucket-32 K2A vid 3 hot role cut at equal cost weight on warp 0 + hot_w4 8)",
        False),
    2: (ROOT / "kernels/muse_decode_layer/k3_m32_2.py", "k3-m32-2",
        "# nonce k3-m32-2 (k3_m32_1 + PX at bucket 32: finalize-free ticket-driven W2 queue starting under K1's tail, "
        "self-tested against vid 3 with fallback)", True),
}


def check(cond, msg):
    if not cond:
        raise SystemExit(f"[gen_k3_m32] FAIL: {msg}")


def _protected(text):
    """Short string constants with a `//` line that the Python code searches for at run time (e.g. _g2_stream_h's
    p1_src.index("// D = 1: <= 64 registers")): strip_cxx would drop that line from the CUDA source and G2's prepare
    then raises 'substring not found' (seen in R-m32-3 prepare logs). Those lines are kept."""
    out = set()
    for n in ast.walk(ast.parse(text)):
        if isinstance(n, ast.Constant) and isinstance(n.value, str) and len(n.value) < 400 and "//" in n.value:
            for line in n.value.splitlines():
                if line.strip().startswith("//"):
                    out.add(line.strip())
    return sorted(out)


def finish(text, nonce, tag, base, rep):
    s1 = strip_layer.strip(text)
    ok, msg = strip_layer.equivalent(text, s1)
    check(ok, f"strip_layer: {msg}")
    prot = _protected(s1)
    lic0 = strip_cxx.LICENSE
    strip_cxx.LICENSE = re.compile("|".join([lic0.pattern] + [re.escape(p) for p in prot]), lic0.flags)
    try:
        s2 = strip_cxx.strip(s1)
        ok2, msg2 = strip_cxx.equivalent(s1, s2)
    finally:
        strip_cxx.LICENSE = lic0
    check(ok2, f"strip_cxx: {msg2}")
    for p in prot:
        check(s2.count(p) == s1.count(p), f"{tag}: strip_cxx dropped a searched-for line {p!r}")
    rep.append(f"{tag}: strip_cxx kept {len(prot)} code-searched // line(s) {prot}")
    rep.append(f"{tag}: {len(text.encode())} -> strip_layer {len(s1.encode())} -> strip_cxx {len(s2.encode())} B")
    tmp = ROOT / f"kernels/muse_decode_layer/{tag}.gen_tmp.py"
    tmp.write_text(s2, encoding="utf-8", newline="\n")
    try:
        py_compile.compile(str(tmp), doraise=True)
    finally:
        tmp.unlink()
    check(s2.isascii(), f"{tag}: non-ASCII character")
    check(s2.split("\n", 1)[0] == "# okc: problem=muse_decode_layer", f"{tag}: line 1")
    check(s2.split("\n")[1] == nonce and s2.count(tag) == 1 and "k3-gd-1" not in s2, f"{tag}: nonce")
    names = [getattr(n, "name", None) or (n.targets[0].id if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)
                                          else None) for n in ast.parse(s2).body]
    dup = sorted({n for n in names if n and names.count(n) > 1})
    check(not dup, f"{tag}: duplicate top-level names {dup}")
    s0, s1s = G37.G.scan(base), G37.G.scan(s2)
    check(all(s1s[k] <= s0[k] for k in s0), f"{tag}: judge-checker scan grew: { {k: (s0[k], s1s[k]) for k in s0 if s1s[k] > s0[k]} }")
    check(len(s2.encode()) < 1_000_000, f"{tag}: file >= 1 MB ({len(s2.encode())} B)")
    rep.append(f"{tag}: compiles, ASCII, line 1, nonce, no duplicate names, checker scan <= base, {len(s2.encode())} B")
    return s2


def main():
    v39, base, rep = G37.generate()
    check(G37.V39 and v39 == GD.V39.read_text(encoding="utf-8"), "gen_k3_v37 --v39 does not reproduce k3_v39.py on disk")
    gd = gd_patches.apply(v39)
    check(gd.count(G37.NONCE) == 1, "k3_v39 nonce line")
    gd = gd.replace(G37.NONCE, GD.NONCE)
    check(strip_layer.strip(gd) == GD1.read_text(encoding="utf-8"), "the gd chain does not reproduce k3_gd_1.py on disk")
    rep.append(f"k3_gd_1 reproduced ({len(GD1.read_bytes())} B)")
    out = {}
    for n, (path, tag, nonce, px) in OUTS.items():
        if ONLY and n != ONLY:
            continue
        t = m32_patches.apply(gd, px=px)
        check(t.count(GD.NONCE) == 1, "gd nonce line")
        t = t.replace(GD.NONCE, nonce)
        out[n] = (path, finish(t, nonce, tag, base, rep))
    for r in rep:
        print(f"[gen_k3_m32] OK  {r}")
    for n, (path, s) in out.items():
        if CHECK:
            check(path.exists() and path.read_text(encoding="utf-8") == s, f"{path.name} on disk differs (regenerate)")
            print(f"[gen_k3_m32] --check: {path.name} up to date")
        else:
            lab = ROOT / "kernels/lab" / (path.stem + "_ab.py")   # byte-identical copy for the box (fresh sync profile)
            path.write_text(s, encoding="utf-8", newline="\n")
            lab.write_text(s, encoding="utf-8", newline="\n")
            print(f"[gen_k3_m32] wrote {path.relative_to(ROOT)} and {lab.relative_to(ROOT)} ({len(s.encode())} B, "
                  f"sha1 {hashlib.sha1(s.encode()).hexdigest()[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
