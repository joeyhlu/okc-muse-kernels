def generate():
    base = BASE.read_text(encoding="utf-8")
    lines = base.split("\n")
    check(lines[1].startswith(HDR_OLD_PREFIX), "base nonce line")
    j = 2
    while lines[j].startswith("#"):
        j += 1
    text = "\n".join(lines[:1]) + "\n" + HDR_NEW + "\n".join(lines[j:])
    text = patch(text, DOC_OLD, DOC_NEW, "docstring")
    for what, old, new in PATCHES:
        text = patch(text, old, new, what)
    if USE_FA4_V7:   # the vendored FA4 block, verbatim v6 -> verbatim v7 (same interface: k1fa4_run / fwd_partials / self_test ...)
        text = patch(text, FA4_V6.read_text(encoding="utf-8"), FA4_V7.read_text(encoding="utf-8"), "FA4 v6 -> v8 (FP8 PV + fat combine)")
    if USE_K2A40:
        for what, old, new in K2A40.PATCHES:
            text = patch(text, old, new, "K2A v4.0 " + what)
    if USE_K2A41 and K2A41_FILE.exists():
        _s41 = importlib.util.spec_from_file_location("k2a_v41_patches", K2A41_FILE)
        K2A41 = importlib.util.module_from_spec(_s41)
        _s41.loader.exec_module(K2A41)
        for what, old, new in K2A41.PATCHES:
            text = patch(text, old, new, "K2A v4.1 " + what)
    if USE_K2A42 and K2A42_FILE.exists():
        _s42 = importlib.util.spec_from_file_location("k2a_v42_patches", K2A42_FILE)
        K2A42 = importlib.util.module_from_spec(_s42)
        _s42.loader.exec_module(K2A42)
        for what, old, new in K2A42.PATCHES:
            text = patch(text, old, new, "K2A v4.2 " + what)
    p1m = node_texts(SRC_P1M, P1M_KEEP)
    got = [n for n, _ in p1m if n]
    check(set(got) == set(P1M_KEEP), f"p1m nodes {sorted(set(P1M_KEEP) ^ set(got))}")
    glue = node_texts(SRC_GLUE)
    route = "V20_P1M_ROUTE = " + repr(V20_ROUTE) + "\n"
    gtxt = "".join(t.rstrip("\n") + "\n\n\n" for _, t in glue)
    check(gtxt.count("V20_P1M_ROUTE = {}\n") == 1, "glue route placeholder")
    gtxt = gtxt.replace("V20_P1M_ROUTE = {}\n", route)
    section = BANNER + "".join(t.rstrip("\n") + "\n\n\n" for _, t in p1m) + v20_pack_text(base).rstrip("\n") + "\n\n\n" + gtxt
    text = patch(text, ANCHOR, section + ANCHOR, "V20 section")
    return text, base


def verify(text, base):
    rep = []
    tmp = OUT.with_suffix(".py.gen_tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    try:
        py_compile.compile(str(tmp), doraise=True)
    finally:
        tmp.unlink()
    check(text.isascii(), "non-ASCII character in the output")
    check(text.count(NONCE) == 1 and "k3-v19-1" not in text and "k3-v18-1" not in text, "nonce")
    hits = {k: v for k, v in G18.scan_text(text).items() if v}
    base_hits = {k: v for k, v in G18.scan_text(base).items() if v}
    check(set(hits) == set(base_hits) and all(len(hits[k]) == len(base_hits[k]) for k in hits),
          f"checker scan differs from the base: { {k: v[:3] for k, v in hits.items()} } vs { {k: v[:3] for k, v in base_hits.items()} }")
    rep.append(f"compiles; checker-scan hits identical to the base ({sorted(hits) or 'none'})")
    tree = ast.parse(text)
    names = [getattr(n, "name", None) or (n.targets[0].id if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) else None)
             for n in tree.body]
    dup = sorted({n for n in names if n and names.count(n) > 1})
    check(not dup, f"duplicate top-level names {dup}")
    for n in ("_v20_p1m", "_v20_prepare", "_v20_p1_pack", "p1m_call", "P1M_CUDA_ADD", "V20_P1M_ROUTE"):
        check(n in names, f"missing {n}")
    rep.append(f"{len(PATCHES)} patches applied once each: " + "; ".join(p[0] for p in PATCHES))
    rep.append(f"V20 section: {len(P1M_KEEP)} p1m_module nodes + _v20_p1_pack + v20_p1m.py; routes {V20_ROUTE}")
    check(len(text.encode()) < 1_000_000, "file >= 1 MB")
    rep.append(f"{len(text.encode())} bytes (< 1 MB)")
    return rep


def main(argv):
    text, base = generate()
    for r in verify(text, base):
        print(f"[gen_k3_v20] OK  {r}")
    if "--check" in argv:
        check(OUT.exists() and OUT.read_text(encoding="utf-8") == text, f"{OUT.name} on disk differs (regenerate)")
        print(f"[gen_k3_v20] --check: up to date (sha1 {sha(text)[:12]})")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"[gen_k3_v20] wrote {OUT.relative_to(ROOT)} (sha1 {sha(text)[:12]}, {len(text.splitlines())} lines, {len(text.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
