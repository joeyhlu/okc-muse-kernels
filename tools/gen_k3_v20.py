def node_texts(path, keep=None, skip_imports=True):
    """[(name or None, text)] of top-level nodes, in file order. keep: names to take (a For loop right after a kept node rides
    along: P1M_KPERM's fill loop). Imports and the module docstring are dropped (the layer has its own)."""
    src = path.read_text(encoding="utf-8")
    lines = src.splitlines(keepends=True)
    tree = ast.parse(src)
    out, prev_kept = [], False
    for i, node in enumerate(tree.body):
        if isinstance(node, (ast.Import, ast.ImportFrom)) or (i == 0 and isinstance(node, ast.Expr)):
            prev_kept = False
            continue
        name = None
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            name = node.name
        elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
        if isinstance(node, ast.For) and prev_kept:
            take = True
        else:
            take = keep is None or name in keep
        start = node.lineno - 1
        if getattr(node, "decorator_list", None):
            start = node.decorator_list[0].lineno - 1
        # pull in the comment block right above the node
        while start > 0 and lines[start - 1].lstrip().startswith("#"):
            start -= 1
        if take:
            out.append((name, "".join(lines[start:node.end_lineno])))
        prev_kept = take
    return out


def v20_pack_text(base):
    """The layer's p1_pack as _v20_p1_pack with the k-permuted lane map (the only change, asserted)."""
    i = base.index("def p1_pack(w, esc_max=P1_ESC_MAX, raw_group=P1_RAW_GROUP, name=\"w\"):\n")
    j = base.index("\n\n\ndef ", i)
    txt = base[i:j] + "\n"
    check(txt.count("    row, kk = p1_lane_maps(dev)\n") == 1, "p1_pack lane-map line")
    txt = txt.replace("def p1_pack(", "def _v20_p1_pack(", 1).replace("    row, kk = p1_lane_maps(dev)\n", "    row, kk = p1m_lane_maps(dev)   # V20: k-permuted\n")
    return ("# V20: the layer's p1_pack with P1M's k-permuted lane map (generated by tools/gen_k3_v20.py; everything else verbatim)\n" + txt)


