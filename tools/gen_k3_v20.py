"""gen_k3_v20.py: k3_v20.py = k3_v18.py (the scored best, read from disk) + the v20 levers, each a text patch that must hit exactly once.

    python -I tools/gen_k3_v20.py            # writes kernels/muse_decode_layer/k3_v20.py, prints the checks
    python -I tools/gen_k3_v20.py --check    # compares with the file on disk, writes nothing

Levers (notes/study/scout/README.md "attention-boundary bundle"; notes/lab.md):
  * K1 merge bank conflict: the [8 warps][8 rows][64] float partial-O store `ow[(warp*8+g)*64 + 8*(2t+e) + jn]` puts the 32 lanes of a warp on 2 banks
    (16-way). The column is XOR-swizzled with (row & 7) on bits 0-2 and (col bit 5) on bit 3: the store's 32 lanes land on 32 banks, the merge read
    (32 consecutive d of one row) stays a permutation inside one 32-float chunk, so it is conflict-free too. Pure layout change: bitwise-same output.
"""

import importlib.util
import pathlib
import py_compile
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "kernels/muse_decode_layer/k3_v20.py"
BASE = ROOT / "kernels/muse_decode_layer/k3_v18.py"
NONCE = "k3-v20-1"

_s18 = importlib.util.spec_from_file_location("gen_k3_v18", ROOT / "tools/gen_k3_v18.py")
G18 = importlib.util.module_from_spec(_s18)
_s18.loader.exec_module(G18)
check, patch, sha = G18.G.check, G18.G.patch, G18.G.sha

HDR_OLD_PREFIX = "# nonce k3-v18-1 "
HDR_NEW = (f"# nonce {NONCE} (k3_v18 + the v20 levers listed in tools/gen_k3_v20.py)\n"
           "# GENERATED by tools/gen_k3_v20.py from kernels/muse_decode_layer/k3_v18.py (text patches, each asserted to hit once). Do not hand-edit:\n"
           "# change a canonical source or a generator and regenerate.\n")
DOC_OLD = '"""K3 v18 = k3_v17 with the FA4 attention path replaced by K1-FA4 v6'
DOC_NEW = ('"""K3 v20 = k3_v18 + the v20 levers (tools/gen_k3_v20.py): K1 merge partial-O store XOR-swizzled (16-way bank conflict removed).\n\n'
           'K3 v18 = k3_v17 with the FA4 attention path replaced by K1-FA4 v6')

PATCHES = [
    ("K1 merge store swizzle",
     "      for (int e = 0; e < 2; ++e) ow[(warp * 8 + g) * 64 + 8 * (2 * t + e) + jn] = o[jn][e];\n",
     "      for (int e = 0; e < 2; ++e) ow[(warp * 8 + g) * 64 + ((8 * (2 * t + e) + jn) ^ g ^ ((t >> 1) << 3))] = o[jn][e];   // v20: XOR swizzle, 32 banks\n"),
    ("K1 merge read swizzle",
     "        acc += f * ow[(w * 8 + r) * 64 + d];\n",
     "        acc += f * ow[(w * 8 + r) * 64 + (d ^ r ^ (((d >> 5) & 1) << 3))];\n"),
]


def generate():
    base = BASE.read_text(encoding="utf-8")
    lines = base.split("\n")
    check(lines[1].startswith(HDR_OLD_PREFIX), "k3_v18 nonce line")
    j = 2
    while lines[j].startswith("#"):
        j += 1
    text = "\n".join(lines[:1]) + "\n" + HDR_NEW + "\n".join(lines[j:])
    text = patch(text, DOC_OLD, DOC_NEW, "docstring")
    for what, old, new in PATCHES:
        text = patch(text, old, new, what)
    return text, base


def verify(text, base):
    rep = []
    tmp = OUT.with_suffix(".py.gen_tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    try:
        py_compile.compile(str(tmp), doraise=True)
    finally:
        tmp.unlink()
    check(text.isascii(), "non-ASCII character in the output")
    check(text.count(NONCE) == 1 and "k3-v18-1" not in text, "nonce")
    hits = {k: v for k, v in G18.scan_text(text).items() if v}
    base_hits = {k: v for k, v in G18.scan_text(base).items() if v}
    check(set(hits) == set(base_hits) and all(len(hits[k]) == len(base_hits[k]) for k in hits),
          f"checker scan differs from k3_v18: {hits} vs {base_hits}")
    rep.append(f"compiles; checker-scan hits identical to k3_v18 ({sorted(hits) or 'none'})")
    rep.append(f"{len(PATCHES)} patches applied once each: " + "; ".join(p[0] for p in PATCHES))
    check(len(text.encode()) < 1_000_000, "file >= 1 MB")
    rep.append(f"{len(text.encode())} bytes (< 1 MB)")
    return rep


def main(argv):
    text, base = generate()
    for r in verify(text, base):
        print(f"[gen_k3_v20] OK  {r}")
    if "--check" in argv:
        check(OUT.exists() and OUT.read_text(encoding="utf-8") == text, f"{OUT.name} on disk differs (regenerate)")
        print(f"[gen_k3_v20] --check: up to date (sha1 {sha(text)[:12]})")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"[gen_k3_v20] wrote {OUT.relative_to(ROOT)} (sha1 {sha(text)[:12]}, {len(text.splitlines())} lines, {len(text.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
