"""Best measured speedup per (problem, shape) across every finished okc result, and which file got it.

  python3 -I tools/best_table.py            # prints the table and writes notes/best_per_shape.md

Speedups are the judge's per-shape paired ratios (SGLang / ours in the same run), so runs on different days and
nodes compare fairly. 'composite' is what a file routing every shape to its best measured path would score
(weighted per-load times, geomean over loads), using each shape's best ratio against the median SGLang time.
"""
import json
import math
import pathlib
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "kernels" / "results"


def shape_key(c):
    return (c.get("load", ""), c.get("layer", c.get("bs", "")), c.get("q_len", 1), c.get("batch", c.get("bs", c.get("m"))), c.get("ctx", ""))


def main():
    files = {}
    for l in (ROOT / "notes" / "jobs.jsonl").read_text().splitlines():
        r = json.loads(l)
        if r.get("job"):
            files[r["job"]] = r["file"]
    best = defaultdict(dict)          # problem -> key -> (speedup, file, sglang_us, weight)
    sgl = defaultdict(lambda: defaultdict(list))
    overall = defaultdict(list)
    for p in sorted(RESULTS.glob("*.json")):
        d = json.loads(p.read_text())
        r = d.get("result") or {}
        if not r.get("passed"):
            continue
        prob = d.get("board")
        overall[prob].append((r.get("speedup") or 0, files.get(d.get("id"), d.get("id"))))
        for x in r.get("records") or []:
            if x.get("event") != "benchmark":
                continue
            c = x["case"]
            k = shape_key(c)
            sp = x.get("speedup") or (x["baseline_ns"] / x["median_ns"] if x.get("median_ns") else None)
            if sp is None:
                continue
            sgl[prob][k].append(x["baseline_ns"] / 1000)
            cur = best[prob].get(k)
            if cur is None or sp > cur[0]:
                best[prob][k] = (sp, files.get(d.get("id"), d.get("id")), None, c.get("weight", 1))
    out = ["# best_per_shape.md — best measured per-shape speedup (generated by tools/best_table.py)", ""]
    for prob in sorted(best):
        rows = best[prob]
        out.append(f"## {prob}   (best whole-file run: {max(overall[prob])[0]:.3f}× {max(overall[prob])[1]})")
        out.append("| load | layer/bs | L | B | ctx | SGLang µs (median) | best speedup | file |")
        out.append("|---|---|---|---|---|---|---|---|")
        loads = defaultdict(lambda: [0.0, 0.0])
        for k in sorted(rows, key=str):
            sp, f, _, w = rows[k]
            s_us = sorted(sgl[prob][k])[len(sgl[prob][k]) // 2]
            loads[k[0]][0] += w * s_us
            loads[k[0]][1] += w * s_us / sp
            out.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {s_us:.1f} | {sp:.3f} | {pathlib.Path(f).name} |")
        if loads:
            g = math.exp(sum(math.log(a / b) for a, b in loads.values()) / len(loads))
            out.append(f"composite if every shape takes its best measured path: **{g:.3f}×**")
        out.append("")
    text = "\n".join(out)
    (ROOT / "notes" / "best_per_shape.md").write_text(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
