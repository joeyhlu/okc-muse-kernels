def once(s, a, b):
    if s.count(a) != 1:
        raise ValueError(f"anchor count {s.count(a)}: {a[:100]!r}")
    return s.replace(a, b, 1)


def source_constants(src):
    wanted = {"GD_CUDA_SRC", "KS1_CUDA_SRC"}
    out = {}
    for n in ast.parse(src).body:
        if isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name) and n.targets[0].id in wanted:
            out[n.targets[0].id] = ast.literal_eval(n.value)
    if set(out) != wanted:
        raise ValueError("base must contain literal GD and KS1 sources")
    return out


def cuda_source(src, torch=True):
    ns = source_constants(src)
    ns["S6A6_CUDA_CORE"] = CORE
    fn = next(n for n in ast.parse(GLUE).body if isinstance(n, ast.FunctionDef) and n.name == "_s6a6_cuda")
    exec(compile(ast.Module(body=[fn], type_ignores=[]), "s6a6-source", "exec"), ns)
    cu = ns["_s6a6_cuda"]()
    if not torch:
        cu = cu.split("// S6A6_TORCH\n")[0]
        cu = "\n".join(x for x in cu.splitlines() if not any(y in x for y in ("#include <torch/", "#include <ATen/", "#include <c10/"))) + "\n"
    return cu


def front_region(src):
    if src.count(FRONT_A) != 1 or src.count(FRONT_Z) != 1:
        raise ValueError("front dispatch anchors changed")
    return src[src.index(FRONT_A):src.index(FRONT_Z)]


def generate(src, ship=False):
    if BEGIN in src:
        raise ValueError("S6A6 already applied")
    source_constants(src)
    cuda_source(src, torch=False)
    old = front_region(src)
    replacement = (' attn_output=_s6a6_try(adata,state) if S6A6 else None\n if attn_output is None:\n'
                   + "".join(" " + ln if ln.strip() else ln for ln in old.splitlines(True))
                   + ' else:\n  state["_ax1_ran"]=False\n')
    result = once(src, old, replacement)
    result = once(result, PREP, PREP_NEW)
    block = BEGIN + GLUE + "\nS6A6_CUDA_CORE = r'''" + CORE + "'''\n" + END
    result = once(result, "def kernel_fn(data,state):\n", block + "def kernel_fn(data,state):\n")
    ast.parse(result)
    if ship and len(result.encode()) >= LIMIT:
        raise ValueError(f"ship size {len(result.encode())} >= {LIMIT}; required fallback cannot be removed")
    # Restore exact original bytes, including all off-target dispatch and source strings.
    restored = once(result, block, "")
    restored = once(restored, PREP_NEW, PREP)
    restored = once(restored, replacement, old)
    if restored != src:
        raise AssertionError("selector-off reconstruction differs from base")
    return result


def check(base, lab, ship):
    expected = generate(base)
    assert lab == expected, "lab is stale"
    assert ship == generate(base, ship=True), "ship is stale"
    tree = ast.parse(lab)
    compile(lab, "s6a6-lab", "exec")
    compile(ship, "s6a6-ship", "exec")
    selector = [n for n in tree.body if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "S6A6" for t in n.targets)]
    assert len(selector) == 1 and ast.literal_eval(selector[0].value) == 0
    return {"selector_default": 0, "off_reconstruction": "byte_exact", "base_bytes": len(base.encode()),
            "lab_bytes": len(lab.encode()), "ship_bytes": len(ship.encode()), "net_bytes": len(ship.encode())-len(base.encode()),
            "base_sha256": hashlib.sha256(base.encode()).hexdigest(), "ship_sha256": hashlib.sha256(ship.encode()).hexdigest()}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--base", type=Path, default=BASE)
    p.add_argument("--out", type=Path)
    p.add_argument("--ship", action="store_true")
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    src = args.base.read_text(encoding="utf-8")
    out = args.out or ROOT / ("kernels/lab/k3_s6a6_ship.py" if args.ship else "kernels/lab/k3_s6a6_ab.py")
    new = generate(src, args.ship)
    if args.check:
        assert out.read_text(encoding="utf-8") == new, "generated output differs"
        print(json.dumps(check(src, generate(src), generate(src, True)), sort_keys=True))
    else:
        out.write_bytes(new.encode("utf-8"))
        print(json.dumps({"out": str(out), "bytes": len(new.encode()), "net_bytes": len(new.encode())-len(src.encode()), "selector": 0}))


if __name__ == "__main__":
    main()
