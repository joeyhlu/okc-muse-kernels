def check_ab_json(out, path):
    """ab_v18a.json: ref = K1FA4V6_ENABLE off only (= k3_v14's attention routes), fa4_on = defaults."""
    arms = json.loads(path.read_text())
    default = out.value("K1FA4V6_ENABLE")
    check(default is True, "K1FA4V6_ENABLE default must be True")
    want = {"ref": False, "fa4_on": True}
    check([a["name"] for a in arms] == list(want), f"{path.name}: arms {[a['name'] for a in arms]} != {list(want)}")
    check(arms[0]["set"] == {"K1FA4V6_ENABLE": False}, f"{path.name}: variant 0 must be ref = K1FA4V6_ENABLE off only")
    rows = []
    for a in arms:
        eff = default
        for k, v in a.get("set", {}).items():
            check(k == "K1FA4V6_ENABLE" and isinstance(v, bool), f"{path.name} {a['name']}: unknown or non-bool switch {k}")
            eff = v
        check(eff is want[a["name"]], f"{path.name} {a['name']}: K1FA4V6_ENABLE resolves to {eff}, want {want[a['name']]}")
        rows.append(f"{a['name']}: K1FA4V6_ENABLE {'on' if eff else 'off'}" + ("" if eff else " (= k3_v14 attention routes: K1 v4 / v7, r1)"))
    return rows


