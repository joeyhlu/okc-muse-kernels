def bound_names(tree):
    """Module-scope bindings (assignments, defs, imports, also inside module-level if / try / with / for), with the binding statement's source."""
    names = {}

    def tgt(t, node):
        if isinstance(t, ast.Name):
            names.setdefault(t.id, []).append(node)
        elif isinstance(t, (ast.Tuple, ast.List)):
            for e in t.elts:
                tgt(e, node)
        elif isinstance(t, ast.Starred):
            tgt(t.value, node)

    def walk(body):
        for n in body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names.setdefault(n.name, []).append(n)
            elif isinstance(n, ast.Assign):
                for t in n.targets:
                    tgt(t, n)
            elif isinstance(n, (ast.AnnAssign, ast.AugAssign)):
                tgt(n.target, n)
            elif isinstance(n, ast.Import):
                for a in n.names:
                    names.setdefault(a.asname or a.name.split(".")[0], []).append(n)
            elif isinstance(n, ast.ImportFrom):
                for a in n.names:
                    names.setdefault(a.asname or a.name, []).append(n)
            elif isinstance(n, (ast.If, ast.While)):
                walk(n.body)
                walk(n.orelse)
            elif isinstance(n, (ast.For, ast.AsyncFor)):
                tgt(n.target, n)
                walk(n.body)
                walk(n.orelse)
            elif isinstance(n, (ast.With, ast.AsyncWith)):
                for it in n.items:
                    if it.optional_vars is not None:
                        tgt(it.optional_vars, n)
                walk(n.body)
            elif isinstance(n, ast.Try):
                walk(n.body)
                for h in n.handlers:
                    walk(h.body)
                walk(n.orelse)
                walk(n.finalbody)
    walk(tree.body)
    return names


