def route_table(out, v17_routed):
    """Evaluate the layer's _v18_fa4_wanted (cfg part and switches) off-GPU on (layer, L, B) and compare with k3_v17's route table (G16.routed)."""
    ns = {"torch": type("T", (), {"bfloat16": "bf16", "int32": "i32"}), "FP8": "fp8", "ROPE_THETA": 500_000.0, "K1FA4_STATE": {"ready": True}}
    for nm in ("K1FA4V6_ENABLE", "K1FA4V6_DECODE_SLIDING", "K1FA4V6_DECODE_FULL_B1", "K1FA4V6_VERIFY_SLIDING", "K1FA4V6_VERIFY_FULL", "K1FA4V6_VERIFY_FULL_MIN_BATCH"):
        ns[nm] = out.value(nm)
    for nm in ("k1fa4_supported", "k1fa4_route_ok", "_v18_fa4_wanted"):
        exec(compile(ast.Module(body=[out.nodes[nm]], type_ignores=[]), "<gen>", "exec"), ns)   # noqa: S102 (repo code)
    qkv = _Stub("bf16")
    data = {"k_cache": _Stub("fp8"), "v_cache": _Stub("fp8"), "page_table": _Stub("i32"), "cache_seqlens": _Stub("i32", 1), "cache_loc": _Stub("i64", 1),
            "positions": _Stub("i64", 1)}
    rows = []
    for layer in ("sliding", "full"):
        for L in (1, 8):
            for B in (1, 2, 3, 5, 9, 15, 16, 17, 32, 33):
                cfg = {"q_len": L, "page_size": 1, "kv_scale": 1.0, "head_dim": 64, "num_q_heads": 16, "num_kv_heads": 2, "batch": B,
                       "window": WINDOW if layer == "sliding" else 0, "rope_theta": 500_000.0 if layer == "sliding" else 0.0}
                got = bool(ns["_v18_fa4_wanted"](qkv, data, cfg, {"fa4v6": True}))
                want = bool(v17_routed(layer, L, B))
                check(got == want, f"route ({layer}, L={L}, B={B}): v18 {got} vs k3_v17 {want}")
                rows.append((layer, L, B, got))
    # a failed prepare / switch off / odd configs keep the old routes
    cfg = {"q_len": 8, "page_size": 1, "kv_scale": 1.0, "head_dim": 64, "num_q_heads": 16, "num_kv_heads": 2, "batch": 16, "window": WINDOW, "rope_theta": 500_000.0}
    check(not ns["_v18_fa4_wanted"](qkv, data, cfg, {"fa4v6": False}) and not ns["_v18_fa4_wanted"](qkv, data, cfg, {}), "state['fa4v6'] False / missing must not route")
    ns["K1FA4_STATE"]["ready"] = False
    check(not ns["_v18_fa4_wanted"](qkv, data, cfg, {"fa4v6": True}), "K1FA4_STATE['ready'] False must not route")
    ns["K1FA4_STATE"]["ready"] = True
    for bad in ({"page_size": 16}, {"kv_scale": 0.5}, {"head_dim": 128}, {"q_len": 4}, {"rope_theta": 10000.0}):
        check(not ns["_v18_fa4_wanted"](qkv, data, dict(cfg, **bad), {"fa4v6": True}), f"config {bad} must not route")
    return len([r for r in rows if r[3]]), len(rows)


def scan_text(text):
    hits = {}
    for label, pat in SCAN:
        found = [(text.count("\n", 0, m.start()) + 1, text[text.rfind("\n", 0, m.start()) + 1:text.find("\n", m.start())].strip()[:110]) for m in re.finditer(pat, text)]
        hits[label] = found
    return hits


