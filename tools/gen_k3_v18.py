def v6_model(v6):
    """The pure functions / tables of the v6 text the coverage model needs (executed from their AST nodes)."""
    ns = {}
    tree = ast.parse(v6)
    want = {"K1FA4_TILE", "K1FA4_MAX_SPLITS", "K1FA4_SPLITS", "K1FA4_SELF_TEST", "k1fa4_num_splits_heuristic", "k1fa4_num_splits_for"}
    body = [n for n in tree.body if (isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id in want for t in n.targets))
            or (isinstance(n, ast.FunctionDef) and n.name in want)]
    check({getattr(n, "name", None) or n.targets[0].id for n in body} == want, "v6 model nodes")
    exec(compile(ast.Module(body=body, type_ignores=[]), "<gen>", "exec"), ns)   # noqa: S102 (repo code)
    return ns


def jit_analysis(v6, warm):
    """Which routed scored shapes' Triton / split-class keys the self-test (v6's cases + warm cases) compiles. Same model as gen_k3_v16.jit_checks:
    FA4 forward compile key separates local from full only; Triton prologue key = (RoPE, BLOCK_M, class of n_rows), combine key = (class of ns / B / L,
    next_pow2(ns), num_warps), class = '1' | 'D' (multiple of 16) | '-'. Returns (uncovered scored shapes, report lines)."""
    ns_ = v6_model(v6)
    nsf, splits = ns_["k1fa4_num_splits_for"], ns_["K1FA4_SPLITS"]

    def cls(v):
        return "1" if v == 1 else ("D" if v % 16 == 0 else "-")

    def pkey(window, L, B):
        n_rows = B * L * (HQ + 2 * HKV)
        return ("rope" if window else "norope", 4 if n_rows < 1024 else (8 if n_rows < 8192 else 16), cls(n_rows))

    def ckey(window, L, B, width):
        keys = min(width, WINDOW + L) if window else width
        ns = splits.get(("sliding" if window else "full", B)) or nsf(B, HKV, keys)
        return (cls(ns), cls(B), cls(L), 1 << (ns - 1).bit_length(), 2 if ns <= 8 else 4), ns

    meta = json.loads(META.read_text(encoding="utf-8"))
    scored = {}
    for b in meta["benchmarks"]:
        L, B, ctx = b.get("q_len", 1), b["batch"], b["ctx"]
        window = WINDOW if b["layer"] == "sliding" else 0
        longest = ctx if b.get("spread", "fixed") == "fixed" else math.ceil(ctx * 1.075)   # reference._longest ("agentic" spread 0.075)
        routed = window or L == 8 or B <= 1   # k1fa4_route_ok
        if routed and not window and L == 8:
            routed = B == 1 or B >= 16        # the layer's full-verify batches
        if routed:
            ck, ns = ckey(window, L, B, longest + L)
            scored[(b["layer"], L, B)] = (pkey(window, L, B), ck, ns)
    check(len(scored) == 10, f"routed scored shapes: {sorted(scored)}")
    cov_p, cov_c = set(), set()
    for batch, ctx, length, window, _seed, _row0 in list(ns_["K1FA4_SELF_TEST"]) + list(warm):
        cov_p.add(pkey(window, length, batch))
        cov_c.add(ckey(window, length, batch, ctx + length)[0])   # _k1fa4_case: page-table width = ctx + length
    miss = [s for s, (pk, ck, _n) in sorted(scored.items()) if pk not in cov_p or ck not in cov_c]
    sc = {f"{l[0]}{L}B{B}": ns for (l, L, B), (_p, _c, ns) in sorted(scored.items())}
    return miss, [f"JIT configs (estimate, Triton's int specialization model): FA4 forward x2 (full, local); Triton prologue {len(cov_p)} keys, combine {len(cov_c)} keys "
                  f"compiled by the self-test; routed scored shapes not covered: {miss or 'none'} (scored split counts {sc}); the judge's capture() warms any other shape eagerly first"]


